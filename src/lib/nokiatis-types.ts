/**
 * Nokiatis MUC — shared domain types for the v1.17.3-beta.1 web launcher.
 *
 * Everything the launcher, the AI engine, the audio engine and the cloud
 * sync layer exchange is typed here so each module can stay isolated.
 */

import type { Track, HistoryEntry, Playlist } from "./nokiatis-cloud";

// ---------------------------------------------------------------------------
// App identity
// ---------------------------------------------------------------------------

export const APP_NAME = "Nokiatis MUC";
export const APP_VERSION = "1.17.3-beta.1";
export const APP_VERSION_CODE = 1170301;
export const APP_CHANNEL = "beta";

// ---------------------------------------------------------------------------
// Rich catalog model (extends the lean cloud Track)
// ---------------------------------------------------------------------------

export interface ArtistInfo {
  id: string;
  name: string; // Arabic display name
  latinName: string;
  genre: string;
  image: string; // /artists/xxx.png
  monthlyListeners: number;
  bio: string; // short Arabic bio
}

export interface RichTrack extends Track {
  artistId: string;
  album: string;
  genre: string;
  year: number;
  durationSec: number;
  /** 0..1 — how energetic the track feels. Feeds the AI mood matching. */
  energy: number;
  /** 0..1 — 0 = calm/late night, 1 = party. */
  mood: number;
  /** Deterministic index into the cover gradient palette. */
  coverSeed: number;
  /** Stable seed for the Web Audio melody generator. */
  synthSeed: number;
}

// ---------------------------------------------------------------------------
// AI — listening events & taste profile
// ---------------------------------------------------------------------------

export interface ListeningEvent {
  id: string;
  trackId: string;
  /** epoch ms when the play session ended */
  ts: number;
  /** how many seconds actually played */
  playedSec: number;
  /** full track duration at the time of the event */
  durationSec: number;
  completed: boolean;
  skipped: boolean;
}

export interface TasteProfile {
  version: 1;
  updatedAt: number;
  totalPlays: number;
  totalSeconds: number;
  avgCompletion: number; // 0..1
  likedTracks: number;
  /** artist name -> normalised affinity 0..100 */
  artistAffinity: Record<string, number>;
  /** genre -> normalised affinity 0..100 */
  genreAffinity: Record<string, number>;
  /** track id -> affinity 0..100 */
  trackAffinity: Record<string, number>;
  topHour: number; // 0..23 hour with most plays
  /** Shannon-like diversity over artist distribution 0..1 */
  diversity: number;
  /** share of plays spent on artists heard for the first time, 0..1 */
  exploration: number;
  /** 0..1 — how concentrated the taste is on the top 3 artists */
  loyalty: number;
  /** consecutive days with at least one play */
  streakDays: number;
}

export interface AiEngineStats {
  totalEvents: number;
  tracksHeard: number;
  catalogCoverage: number; // 0..1
  artistsHeard: number;
  genresHeard: number;
  topArtists: { name: string; score: number; plays: number }[];
  topGenres: { name: string; score: number; plays: number }[];
  favoriteHourLabel: string;
  completionLabel: string;
}

// ---------------------------------------------------------------------------
// Smart playlists generated by the AI engine
// ---------------------------------------------------------------------------

export type SmartKind = "daily" | "discover" | "rewind" | "energy" | "calm";

export interface SmartPlaylist {
  id: string;
  kind: SmartKind;
  title: string;
  subtitle: string;
  trackIds: string[];
  /** hex accent for the card gradient */
  accent: string;
  icon: string; // lucide icon name resolved by the UI
}

// ---------------------------------------------------------------------------
// Local settings / identity / notifications / sync log
// ---------------------------------------------------------------------------

export interface AppSettings {
  audioQuality: "normal" | "high";
  bass: number; // -12..12 dB
  treble: number; // -12..12 dB
  normalization: boolean;
  surround: boolean;
  notifyUpdates: boolean; // stable channel
  notifyBeta: boolean; // beta channel
  notifyInApp: boolean;
  betaChannelEnabled: boolean; // app-level: check beta releases at all
  crossfadeSec: number; // 0..8 (applied by the engine as fade-out)
}

export interface ProfileIdentity {
  name: string;
  colorIndex: number; // avatar color palette index
  emoji: string; // small flair on the avatar
}

export type NotificationKind =
  | "update-beta"
  | "update-stable"
  | "ai"
  | "sync"
  | "info";

export interface NotificationItem {
  id: string;
  ts: number;
  kind: NotificationKind;
  title: string;
  body: string;
  read: boolean;
  version?: string;
}

export interface SyncLogEntry {
  id: string;
  ts: number;
  dir: "up" | "down" | "error";
  summary: string;
  ok: boolean;
}

export interface VaultConfig {
  enabled: boolean;
  /** simple non-cryptographic hash — the vault is a UI gate, not DRM */
  pinHash: string;
  hint: string;
}

// ---------------------------------------------------------------------------
// Update channels (mirrors nokiatis-muc-updates repo shape, defensively)
// ---------------------------------------------------------------------------

export interface UpdateInfo {
  channel: "stable" | "beta";
  versionName: string;
  versionCode: number;
  releaseDate: string;
  notes: string;
  downloadUrl: string;
  fetchedAt: number;
}

// ---------------------------------------------------------------------------
// Shared playlists — link payload (base64url, no backend required)
// ---------------------------------------------------------------------------

export interface SharedPlaylistPayload {
  n: string; // name
  t: string[]; // "title — artist" entries
  by: string; // sender display name
  v: 1;
}

// ---------------------------------------------------------------------------
// Player state
// ---------------------------------------------------------------------------

export type RepeatMode = "off" | "all" | "one";

export interface PlayerQueue {
  trackIds: string[];
  index: number;
  context: string; // "library" | "playlist:<id>" | "smart:<id>" | "search"
}

export interface PlayerState {
  currentTrackId: string | null;
  playing: boolean;
  positionSec: number;
  durationSec: number;
  volume: number;
  muted: boolean;
  shuffle: boolean;
  repeat: RepeatMode;
}

// ---------------------------------------------------------------------------
// Guest local data bundle (JSON export / import for guest mode)
// ---------------------------------------------------------------------------

export interface GuestBackup {
  kind: "nokiatis-guest-backup";
  version: 1;
  createdAt: number;
  library: {
    liked: Track[];
    saved: Track[];
    downloaded: Track[];
    history: HistoryEntry[];
    playlists: Playlist[];
    listenedSeconds: number;
    listeningEvents: ListeningEvent[];
  };
  profile: TasteProfile | null;
}
